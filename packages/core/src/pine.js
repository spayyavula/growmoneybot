import { OPERANDS, operandLabel } from "./catalog.js";
import { operandKey } from "./evaluate.js";

const num = (v) => {
  const n = Number(v);
  return Number.isInteger(n) ? String(n) : String(+n.toFixed(8));
};
const pineString = (s) => String(s ?? "").replace(/["\\\n\r]/g, " ").slice(0, 80);

/**
 * Generate a TradingView Pine Script v6 strategy equivalent to a builder strategy.
 * options.strategyId is embedded in webhook alert messages so signals can be
 * matched back to the strategy in GrowMoneyBot.
 */
export function generatePine(strategy, { strategyId = "" } = {}) {
  const risk = { initialCapital: 10000, positionSizePct: 100, feePct: 0, stopLossPct: 0, takeProfitPct: 0, ...strategy.risk };
  const isShort = strategy.direction === "short";
  const vars = new Map(); // operandKey -> expression name
  const decls = [];
  const plots = [];
  let counter = 0;

  const exprFor = (op) => {
    const p = op.params || {};
    if (op.type === "value") return num(p.value);
    if (op.type === "price") return p.source || "close";
    if (op.type === "volume") return "volume";

    // Multi-output indicators share one tuple declaration across fields
    const baseKey = operandKey({ ...op, field: null });
    if (!vars.has(baseKey)) {
      counter++;
      const src = p.source || "close";
      const name = `${op.type}${counter}`;
      switch (op.type) {
        case "sma":
        case "ema":
          decls.push(`${name} = ta.${op.type}(${src}, ${num(p.length)})`);
          plots.push(`plot(${name}, "${operandLabel(op)}", color=color.new(color.blue, ${(counter * 25) % 80}))`);
          break;
        case "rsi":
          decls.push(`${name} = ta.rsi(${src}, ${num(p.length)})`);
          break;
        case "atr":
          decls.push(`${name} = ta.atr(${num(p.length)})`);
          break;
        case "macd":
          decls.push(`[${name}_line, ${name}_signal, ${name}_hist] = ta.macd(${src}, ${num(p.fast)}, ${num(p.slow)}, ${num(p.signal)})`);
          break;
        case "bb":
          decls.push(`[${name}_middle, ${name}_upper, ${name}_lower] = ta.bb(${src}, ${num(p.length)}, ${num(p.mult)})`);
          plots.push(`plot(${name}_upper, "BB upper", color=color.gray)`, `plot(${name}_middle, "BB basis", color=color.orange)`, `plot(${name}_lower, "BB lower", color=color.gray)`);
          break;
        case "stoch":
          decls.push(`${name}_k = ta.sma(ta.stoch(close, high, low, ${num(p.kLength)}), ${num(p.kSmooth)})`);
          decls.push(`${name}_d = ta.sma(${name}_k, ${num(p.dSmooth)})`);
          break;
        default:
          throw new Error(`Unsupported operand: ${op.type}`);
      }
      vars.set(baseKey, name);
    }
    const name = vars.get(baseKey);
    return OPERANDS[op.type].fields ? `${name}_${op.field || OPERANDS[op.type].fields[0].key}` : name;
  };

  const condExpr = (c) => {
    const a = exprFor(c.left);
    const b = exprFor(c.right);
    if (c.op === "crossesAbove") return `ta.crossover(${a}, ${b})`;
    if (c.op === "crossesBelow") return `ta.crossunder(${a}, ${b})`;
    return `(${a} ${c.op} ${b})`;
  };

  const groupExpr = (g) => {
    const conds = g?.conditions || [];
    if (!conds.length) return "false";
    return conds.map(condExpr).join(g.logic === "any" ? " or " : " and ");
  };

  const entryExpr = groupExpr(strategy.entry);
  const exitExpr = groupExpr(strategy.exit);

  const id = isShort ? "Short" : "Long";
  const msg = (type, action) =>
    `'{"strategyId":"${pineString(strategyId)}","type":"${type}","action":"${action}","ticker":"' + syminfo.ticker + '","exchange":"' + syminfo.prefix + '","interval":"' + timeframe.period + '","price":' + str.tostring(close) + '}'`;
  const openAction = isShort ? "sell" : "buy";
  const closeAction = isShort ? "buy" : "sell";

  const sl = Number(risk.stopLossPct) || 0;
  const tp = Number(risk.takeProfitPct) || 0;
  const stopExpr = isShort ? `strategy.position_avg_price * (1 + slPct / 100)` : `strategy.position_avg_price * (1 - slPct / 100)`;
  const limitExpr = isShort ? `strategy.position_avg_price * (1 - tpPct / 100)` : `strategy.position_avg_price * (1 + tpPct / 100)`;

  const lines = [
    `// ${pineString(strategy.name)} — generated by GrowMoneyBot (growmoneybot.com)`,
    `// Paste into TradingView's Pine Editor and click "Add to chart".`,
    `// For webhook alerts: create an alert on this strategy, set the message to`,
    `// {{strategy.order.alert_message}} and the webhook URL to your GrowMoneyBot URL.`,
    `// Hypothetical results only. Not financial advice.`,
    ...(strategy.instrument === "options"
      ? [`// Options overlay: in GrowMoneyBot each trade opens an options position (${strategy.options?.structure === "single" ? "long call/put" : "debit spread"}).`,
         `// TradingView strategies can't trade options, so this script trades the stock on the same signals.`,
         `// Use its alerts as the signal to open or close your options position.`]
      : []),
    ...(Number(risk.slippagePct) > 0
      ? [`// Note: the GrowMoneyBot backtest adds ${num(risk.slippagePct)}% slippage per fill. TradingView sets slippage in ticks`,
         `// (Properties → Slippage), so its results here won't include it unless you set that too.`]
      : []),
    `//@version=6`,
    `strategy("${pineString(strategy.name) || "GrowMoneyBot strategy"}", overlay=true,`,
    `     initial_capital=${num(risk.initialCapital)},`,
    `     default_qty_type=strategy.percent_of_equity, default_qty_value=${num(risk.positionSizePct)},`,
    `     commission_type=strategy.commission.percent, commission_value=${num(risk.feePct)})`,
    ``,
    `slPct = input.float(${num(sl)}, "Stop loss %", minval=0, step=0.1)`,
    `tpPct = input.float(${num(tp)}, "Take profit %", minval=0, step=0.1)`,
    ``,
    `// Indicators`,
  ];
  // Build expressions first so declarations are collected
  lines.push("__DECLS__");
  lines.push(
    ``,
    `// Rules (evaluated on bar close, orders fill on the next bar's open)`,
    `entryCond = ${entryExpr}`,
    `exitCond = ${exitExpr}`,
    ``,
    `if entryCond and strategy.position_size == 0`,
    `    strategy.entry("${id}", strategy.${isShort ? "short" : "long"}, alert_message=${msg("entry", openAction)})`,
    ``,
    `if exitCond and strategy.position_size != 0`,
    `    strategy.close("${id}", comment="Exit signal", alert_message=${msg("exit", closeAction)})`,
    ``,
    `if strategy.position_size != 0 and (slPct > 0 or tpPct > 0)`,
    `    strategy.exit("${id} SL/TP", "${id}",`,
    `         stop=slPct > 0 ? ${stopExpr} : na,`,
    `         limit=tpPct > 0 ? ${limitExpr} : na,`,
    `         alert_message=${msg("exit", closeAction)})`,
    ``,
    `// Plots`
  );
  lines.push(...plots);
  lines.push(
    isShort
      ? `plotshape(entryCond and strategy.position_size == 0, "Entry signal", shape.triangledown, location.abovebar, color.red, size=size.tiny)`
      : `plotshape(entryCond and strategy.position_size == 0, "Entry signal", shape.triangleup, location.belowbar, color.green, size=size.tiny)`
  );

  return lines.join("\n").replace("__DECLS__", decls.join("\n"));
}
